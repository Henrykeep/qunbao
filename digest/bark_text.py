# 阶段 5：空白收尾
SPACE_RULES = _compile([
    (r"[\u2002-\u200a\u00a0\u202f]", " ", 0),  # 特殊空格统一成普通空格
    (r"[ \u3000\t]{2,}", " ", 0),  # 连续空格折成一个
    (r" +(?=[，。、；：！？）」』》】])", "", 0),  # 网址/代码被换成占位后留下的「[链接] ，」空格，中文标点前不该有空格
])

STRIP_RULES = NORMALIZE_RULES + MARKUP_RULES + PLACEHOLDER_RULES + WORDING_RULES + SPACE_RULES  # 兼容：测试和调试读全表


def _apply(t: str, rules) -> str:
    for rx, rep in rules:
        t = rx.sub(rep, t)
    return t


def strip_md(t: str) -> str:
    """Bark 不渲染 Markdown，LLM/转发带的标记会原样露在锁屏上：按阶段表顺序清掉。"""
    t = _apply(t or "", NORMALIZE_RULES)
    t = html.unescape(t)  # 换行统一后再解 &amp; &lt;，其后的标签规则才看得见 &lt;b&gt; 还原出的标签
    for rules in (MARKUP_RULES, PLACEHOLDER_RULES, WORDING_RULES, SPACE_RULES):
        t = _apply(t, rules)
    return t.strip()
